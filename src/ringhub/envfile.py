"""Generate a complete .env for the Docker / Pi stack. Standard library only.

Runs with the system Python before anything is installed or built:

    PYTHONPATH=src python3 -m ringhub.envfile --host pi.tail1234.ts.net --tz America/New_York > .env

(``ringhub env`` is the same thing once ringhub is installed.)
"""

from __future__ import annotations

import argparse
import re
import secrets
import sys

_FQDN_RE = re.compile(r"^(?=.{4,253}$)([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")
_TOPIC_ALPHABET = "abcdefghijkmnpqrstuvwxyz23456789"  # no look-alikes (l/1, o/0)


class EnvError(ValueError):
    pass


def normalize_host(host: str) -> str:
    h = host.strip().rstrip(".").lower()
    if h.startswith(("http://", "https://")) or not _FQDN_RE.match(h):
        raise EnvError("--host must be the full Tailscale name, e.g. pi.tail1234.ts.net "
                       "(from: tailscale status --self --json | jq -r .Self.DNSName)")
    return h


def generate(host: str, *, ring_port: int = 8443, ntfy_port: int = 8444, tz: str = "UTC") -> str:
    h = normalize_host(host)
    for port in (ring_port, ntfy_port):
        if not 1 <= port <= 65535:
            raise EnvError(f"port {port} is out of range")
    if ring_port == ntfy_port:
        raise EnvError("ringhub and ntfy need different ports")
    ring = h if ring_port == 443 else f"{h}:{ring_port}"
    ntfy = h if ntfy_port == 443 else f"{h}:{ntfy_port}"
    topic = "ring-" + "".join(secrets.choice(_TOPIC_ALPHABET) for _ in range(12))
    return f"""# Generated by ringhub. Keep this file private (chmod 600 .env).
RINGHUB_SECRET={secrets.token_urlsafe(32)}
RINGHUB_ADMIN_TOKEN={secrets.token_urlsafe(32)}
RINGHUB_CONTEXT_TOKEN={secrets.token_urlsafe(32)}
RINGHUB_PUBLIC_URL=https://{ring}
NTFY_PUBLIC_URL=https://{ntfy}
# Random on purpose: the iPhone push relay keys on a hash of the topic URL.
NTFY_TOPIC={topic}
# Paste the tk_... printed by:  docker compose exec ntfy ntfy token add --label=ringhub ringhub
NTFY_TOKEN=
# Every push at least this priority: 4 alerts through Focus on iPhone, 5 = urgent. 1-2 are silent.
NTFY_MIN_PRIORITY=4
TZ={tz}
# ANTHROPIC_API_KEY=
# TESLA_VIN=
# TESLA_CLIENT_ID=
# TESLA_REFRESH_TOKEN=
"""


def add_arguments(p: argparse.ArgumentParser) -> None:
    p.add_argument("--host", required=True, help="your machine's Tailscale name, e.g. pi.tail1234.ts.net")
    p.add_argument("--ring-port", type=int, default=8443, help="tailnet HTTPS port for ringhub (default 8443)")
    p.add_argument("--ntfy-port", type=int, default=8444, help="tailnet HTTPS port for ntfy (default 8444)")
    p.add_argument("--tz", default="UTC", help="IANA time zone, e.g. America/New_York")


def run(args: argparse.Namespace) -> int:
    try:
        sys.stdout.write(generate(args.host, ring_port=args.ring_port, ntfy_port=args.ntfy_port, tz=args.tz))
    except EnvError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python3 -m ringhub.envfile", description=__doc__.splitlines()[0])
    add_arguments(parser)
    return run(parser.parse_args(argv))


if __name__ == "__main__":
    sys.exit(main())
